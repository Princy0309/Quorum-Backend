import { generateRawCompletion } from './aiService.js';
import { searchAuthorizedWorkspaceRecords, WorkspaceRecord } from './aiRetrievalService.js';

export interface ChatAnswerResponse {
  answer: string;
  metadata: {
    requestId: string;
    model: string;
    createdAt: string;
    tokenUsage?: any;
  };
}

export interface WorkspaceSearchAiResponse {
  query: string;
  answer: string;
  sources: WorkspaceRecord[];
  metadata: {
    requestId: string;
    model: string;
    createdAt: string;
    tokenUsage?: any;
  };
}

export const askAiAssistant = async (
  prompt: string,
  context?: string
): Promise<ChatAnswerResponse> => {
  const systemInstruction = 'You are the intelligent AI Assistant for the Quorum collaboration platform. Provide clear, professional, direct, and actionable answers to assist users with their questions and tasks.';

  let finalPrompt = prompt;
  if (context && context.trim().length > 0) {
    finalPrompt = `Context:\n${context.trim()}\n\nQuestion:\n${prompt}`;
  }

  const completion = await generateRawCompletion(finalPrompt, systemInstruction);

  return {
    answer: completion.text || 'No response generated by the AI model.',
    metadata: {
      requestId: completion.requestId,
      model: completion.model,
      createdAt: new Date().toISOString(),
      tokenUsage: completion.usage
    }
  };
};

export const searchWorkspaceWithAi = async (
  userId: string,
  query: string,
  options?: { limit?: number }
): Promise<WorkspaceSearchAiResponse> => {
  const records = await searchAuthorizedWorkspaceRecords(userId, query, options?.limit);

  if (records.length === 0) {
    return {
      query,
      answer: `No relevant information was found across your authorized messages, posts, or workspace records for "${query}".`,
      sources: [],
      metadata: {
        requestId: 'none',
        model: 'none',
        createdAt: new Date().toISOString()
      }
    };
  }

  let formattedContext = 'Retrieved Workspace Records:\n';
  records.forEach((rec, idx) => {
    formattedContext += `[Record ${idx + 1}] (${rec.type.toUpperCase()}) From ${rec.source} by ${rec.author} on ${rec.createdAt}:\n"${rec.content}"\n\n`;
  });

  const prompt = `${formattedContext}User Search Query: ${query}\n\nPlease synthesize a clear, grounded, and concise answer directly answering the user query using only the records provided above. When stating facts, cite the respective source record like [Record 1]. If certain details are missing from the records, clearly mention what is unavailable.`;

  const systemInstruction = 'You are the Quorum Workspace Knowledge Assistant. Provide direct, factual, well-organized answers grounded in the provided workspace records with source citations.';

  const completion = await generateRawCompletion(prompt, systemInstruction);

  return {
    query,
    answer: completion.text || 'Unable to synthesize response from workspace records.',
    sources: records,
    metadata: {
      requestId: completion.requestId,
      model: completion.model,
      createdAt: new Date().toISOString(),
      tokenUsage: completion.usage
    }
  };
};
