import { generateRawCompletion } from './aiService.js';
import {
  searchAuthorizedWorkspaceRecords,
  WorkspaceRecord,
  getAuthorizedProjectContext
} from './aiRetrievalService.js';

export interface ChatAnswerResponse {
  answer: string;
  metadata: {
    requestId: string;
    model: string;
    createdAt: string;
    tokenUsage?: any;
  };
}

export interface WorkspaceSearchAiResponse {
  query: string;
  answer: string;
  sources: WorkspaceRecord[];
  metadata: {
    requestId: string;
    model: string;
    createdAt: string;
    tokenUsage?: any;
  };
}

export interface ProjectAssistanceResponse {
  prompt: string;
  answer: string;
  project: {
    id: string;
    name: string;
    type: string;
    description: string | null;
    memberCount: number;
    teamCount?: number;
    discussionCount?: number;
  };
  metadata: {
    requestId: string;
    model: string;
    createdAt: string;
    tokenUsage?: any;
  };
}

export const askAiAssistant = async (
  prompt: string,
  context?: string
): Promise<ChatAnswerResponse> => {
  const systemInstruction = 'You are the intelligent AI Assistant for the Quorum collaboration platform. Provide clear, professional, direct, and actionable answers to assist users with their questions and tasks.';

  let finalPrompt = prompt;
  if (context && context.trim().length > 0) {
    finalPrompt = `Context:\n${context.trim()}\n\nQuestion:\n${prompt}`;
  }

  const completion = await generateRawCompletion(finalPrompt, systemInstruction);

  return {
    answer: completion.text || 'No response generated by the AI model.',
    metadata: {
      requestId: completion.requestId,
      model: completion.model,
      createdAt: new Date().toISOString(),
      tokenUsage: completion.usage
    }
  };
};

export const searchWorkspaceWithAi = async (
  userId: string,
  query: string,
  options?: { limit?: number }
): Promise<WorkspaceSearchAiResponse> => {
  const records = await searchAuthorizedWorkspaceRecords(userId, query, options?.limit);

  if (records.length === 0) {
    return {
      query,
      answer: `No relevant information was found across your authorized messages, posts, or workspace records for "${query}".`,
      sources: [],
      metadata: {
        requestId: 'none',
        model: 'none',
        createdAt: new Date().toISOString()
      }
    };
  }

  let formattedContext = 'Retrieved Workspace Records:\n';
  records.forEach((rec, idx) => {
    formattedContext += `[Record ${idx + 1}] (${rec.type.toUpperCase()}) From ${rec.source} by ${rec.author} on ${rec.createdAt}:\n"${rec.content}"\n\n`;
  });

  const prompt = `${formattedContext}User Search Query: ${query}\n\nPlease synthesize a clear, grounded, and concise answer directly answering the user query using only the records provided above. When stating facts, cite the respective source record like [Record 1]. If certain details are missing from the records, clearly mention what is unavailable.`;

  const systemInstruction = 'You are the Quorum Workspace Knowledge Assistant. Provide direct, factual, well-organized answers grounded in the provided workspace records with source citations.';

  const completion = await generateRawCompletion(prompt, systemInstruction);

  return {
    query,
    answer: completion.text || 'Unable to synthesize response from workspace records.',
    sources: records,
    metadata: {
      requestId: completion.requestId,
      model: completion.model,
      createdAt: new Date().toISOString(),
      tokenUsage: completion.usage
    }
  };
};

export const getProjectAssistance = async (
  userId: string,
  prompt: string,
  options?: { organizationId?: string; teamId?: string; communityId?: string }
): Promise<ProjectAssistanceResponse> => {
  const project = await getAuthorizedProjectContext(userId, options);

  let context = `Project Name: ${project.projectName}\n`;
  context += `Project Type: ${project.projectType}\n`;
  if (project.description) {
    context += `Description: ${project.description}\n`;
  }
  context += `Members (${project.members.length}): ${project.members.map((m) => `${m.name} (${m.role})`).join(', ')}\n`;

  if (project.teams && project.teams.length > 0) {
    context += `Teams: ${project.teams.map((t) => t.name).join(', ')}\n`;
  }

  if (project.discussions && project.discussions.length > 0) {
    context += `Recent Updates & Discussions:\n`;
    project.discussions.forEach((d) => {
      context += `- [${d.createdAt}] ${d.author}: ${d.content}\n`;
    });
  }

  const finalPrompt = `Project Context:\n${context}\n\nUser Question/Request:\n${prompt}\n\nPlease provide actionable project-related assistance regarding tasks, updates, decisions, or deadlines based on the provided project information. If specific deadlines or deliverables are not mentioned in the records, state so clearly.`;

  const systemInstruction = 'You are the Quorum Project Assistant. Help team members manage tasks, track project status, review decisions, and plan next steps based on authorized workspace data.';

  const completion = await generateRawCompletion(finalPrompt, systemInstruction);

  return {
    prompt,
    answer: completion.text || 'Unable to generate project assistance.',
    project: {
      id: project.projectId,
      name: project.projectName,
      type: project.projectType,
      description: project.description,
      memberCount: project.members.length,
      teamCount: project.teams?.length,
      discussionCount: project.discussions?.length
    },
    metadata: {
      requestId: completion.requestId,
      model: completion.model,
      createdAt: new Date().toISOString(),
      tokenUsage: completion.usage
    }
  };
};
